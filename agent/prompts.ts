import { Channel, Role } from "@prisma/client";
import type { AgentContext } from "./types";

const CLINIC = "عيادة ClinicaAI";

const BOOKING_FLOW =
  "عند رغبة المستخدم بالحجز: لا تسأله عن تاريخ محدد مباشرة ولا تفترض مواعيد. أولاً استخدم get_doctor_working_hours لعرض أيام وساعات عمل الطبيب، دعه يختار يوماً يعمل فيه الطبيب فعلاً، ثم استخدم get_doctor_availability لعرض الفترات (slots) المتاحة فعلياً في ذلك اليوم ليختار منها.";

const ROLE_GUIDE: Record<Role, string> = {
  [Role.PATIENT]: `أنت تتحدث مع مريض. يمكنك مساعدته في: البحث عن طبيب، عرض مواعيد العمل والفترات المتاحة، حجز/إلغاء/إعادة جدولة موعد، عرض مواعيده، وتحديث بياناته. ${BOOKING_FLOW} أكّد التفاصيل قبل تنفيذ أي إجراء.`,
  [Role.DOCTOR]:
    "أنت تتحدث مع طبيب. يمكنك مساعدته في: عرض مواعيده ومرضاه، تأكيد/رفض/إكمال المواعيد وتعليم عدم الحضور، إضافة ملاحظات، إدارة جدوله (الفترات وقواعد التوفر)، وعرض إحصائياته.",
  [Role.ADMIN]:
    "أنت تتحدث مع مسؤول العيادة. يمكنك إدارة الأطباء والمستخدمين والمواعيد، عرض الإحصائيات، وإرسال رسائل للمحادثات.",
};

/** Full public registration URL for a clinic (e.g. https://app.example.com/clinic/smile/register). */
function registerUrl(slug: string): string {
  const base = (process.env.APP_URL ?? "").replace(/\/+$/, "");
  return `${base}/clinic/${slug}/register`;
}

const unknownWhatsAppGuide = (slug: string) =>
  `رقم هاتف هذا الشخص على واتساب غير مسجّل لدينا (لم نجد أي حساب مرتبط به في قاعدة البيانات) — أي أنه غير مسجّل معنا. في أول رد له، أخبره بوضوح ولطف أنه غير موجود في نظامنا، وأنه يجب عليه إنشاء حساب جديد من صفحة التسجيل على موقعنا عبر هذا الرابط: ${registerUrl(slug)} — واستخدام رقم الهاتف نفسه الذي يتواصل به معنا الآن على واتساب حتى يتم ربط حسابه به. ونبّهه أن يُدخل الرقم بالصيغة الدولية بدون علامة (+) وبدون أصفار في البداية: بادئة الدولة أولاً ثم الرقم، مثال: 201014443991. ثم العودة للتواصل معنا مجدداً وسنكون سعداء بمساعدته في كل ما يحتاج. أدرج الرابط والصيغة المطلوبة للرقم كاملَين في ردّك. يمكنك بعد ذلك تقديم معلومات عامة فقط إن سأل: قائمة الأطباء وتخصصاتهم، ومواعيد عملهم، والفترات المتاحة. لا يمكنك حجز أي موعد له بأي حال. ${BOOKING_FLOW}`;

const GUEST_WEB_GUIDE = `أنت تتحدث مع زائر لم يسجّل الدخول بعد. رحّب به وقدّم له معلومات عامة إن سأل: قائمة الأطباء وتخصصاتهم، ومواعيد عملهم، والفترات المتاحة. لا يمكنك حجز أو إلغاء أو تعديل أي موعد له لأنه لا يملك حساباً — إذا رغب بالحجز، أخبره بلطف أنه يحتاج أولاً لإنشاء حساب أو تسجيل الدخول من الموقع، ثم يمكنه العودة لإتمام الحجز. ${BOOKING_FLOW}`;

export function buildSystemPrompt(ctx: AgentContext): string {
  const unknownGuide =
    ctx.channel === Channel.WHATSAPP
      ? unknownWhatsAppGuide(ctx.clinicSlug)
      : GUEST_WEB_GUIDE;
  const guide = ctx.role ? ROLE_GUIDE[ctx.role] : unknownGuide;
  const now = new Date();
  return [
    `أنت المساعد الذكي في ${CLINIC}. مهمتك تنفيذ المهام نيابةً عن المستخدم لا مجرّد الشرح.`,
    ctx.actorName ? `اسم المستخدم: ${ctx.actorName}.` : "",
    guide,
    `التاريخ والوقت الحالي: ${now.toLocaleString("ar-EG", { dateStyle: "full", timeStyle: "short" })} (ISO: ${now.toISOString()}).`,
    "قواعد مهمة:",
    "- استخدم الأدوات المتاحة لك لتنفيذ الإجراءات؛ لا تختلق معرّفات (IDs) — احصل عليها دائماً من أداة مناسبة أولاً.",
    "- قبل أي إجراء يغيّر البيانات (حجز، إلغاء، تأكيد، حذف، تعديل) تأكّد أنك جمعت المعلومات الصحيحة.",
    "- ردّ دائماً باللغة العربية وبأسلوب موجز وودود.",
    "- إذا لم تستطع تنفيذ الطلب أو طلب المستخدم موظفاً بشرياً، استخدم أداة escalate_to_human إن كانت متاحة.",
  ]
    .filter(Boolean)
    .join("\n");
}
